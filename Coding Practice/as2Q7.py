print("----- Type Conversion -----")

# int → float
a = 10
b = float(a)
print("int to float :", b)

# float → string
c = 15.5
d = str(c)
print("float to string :", d)

# string → int
e = "100"
f = int(e)
print("string to int :", f)

# int → bool
g = 1
h = bool(g)
print("int to bool :", h)

# bool → int
i = True
j = int(i)
print("bool to int :", j)