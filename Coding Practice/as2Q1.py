print("----- Primitive Data Types -----")

# Integer
integer_value = 10
print("Value =", integer_value)
print("Data Type =", type(integer_value))
print("Memory Address =", id(integer_value))

# Float
float_value = 10.5
print("\nValue =", float_value)
print("Data Type =", type(float_value))
print("Memory Address =", id(float_value))

# Complex
complex_value = 2 + 3j
print("\nValue =", complex_value)
print("Data Type =", type(complex_value))
print("Memory Address =", id(complex_value))

# Boolean
boolean_value = True
print("\nValue =", boolean_value)
print("Data Type =", type(boolean_value))
print("Memory Address =", id(boolean_value))

# String
string_value = "Python"
print("\nValue =", string_value)
print("Data Type =", type(string_value))
print("Memory Address =", id(string_value))